#!/usr/bin/env python3
"""Reproducible #124 comparison: Rust walk-forward vs the pinned row-wise Python.

Both programs read the same 3,943,856 x 56 hourly panel projection (the CSV for
Python, the byte-identical `.rcsb` store for Rust), use the same window, score,
target, q70 rule, 10 bp/side cost and 8,760 periods/year. The driver records:

* wall clock and peak RSS for every repeat (`/usr/bin/time -f '%e %M'`);
* the q70 threshold from each side and whether it agrees to 1e-12;
* the median wall ratio and RSS ratio;
* hashes of the CSV, store, Python script and Rust binary, plus the interpreter
  and host, so the artifact is pinned.

The default corpus is the pilot projection under `arbeidsmappe/` (git-ignored);
the protocol and the reason the reference is row-wise are in
`docs/eval-benchmark.md`.

Usage:

    python3 benchmarks/eval_10x.py --repeats 2 \
        --json benchmarks/results/issue-124-eval-10x.json \
        --markdown benchmarks/results/issue-124-eval-10x.md

    # fail if the threshold disagrees or the wall ratio is below 10x
    python3 benchmarks/eval_10x.py --check

The long-form `--check` run is also wrapped by the ignored Rust test
`tests/walkforward_bench.rs::eval_10x_against_pinned_python_reference`.
"""
import argparse
import hashlib
import json
import os
import platform
import shutil
import statistics
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PILOT = os.path.join(ROOT, "arbeidsmappe", "crypto-rcsr", "pilot")
DEFAULT_CSV = os.path.join(PILOT, "panel_hourly_compact.csv")
DEFAULT_STORE = os.path.join(PILOT, "panel_hourly_v2.rcsb")
DEFAULT_RCSR = os.path.join(ROOT, "my-version", "target", "release", "rcsr")
DEFAULT_REFERENCE = os.path.join(HERE, "eval_python_reference.py")
DEFAULT_JSON = os.path.join(HERE, "results", "issue-124-eval-10x.json")
DEFAULT_MARKDOWN = os.path.join(HERE, "results", "issue-124-eval-10x.md")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def timed(command, stdout_path):
    """Run `command`, return (wall_seconds, peak_rss_kib, text)."""
    if not os.path.exists("/usr/bin/time"):
        raise SystemExit("/usr/bin/time is required for a fair RSS measurement")
    fd, time_path = tempfile.mkstemp(prefix="rcsr-time-", text=True)
    os.close(fd)
    try:
        full = ["/usr/bin/time", "-f", "%e %M", "-o", time_path] + command
        t0 = time.perf_counter()
        proc = subprocess.run(full, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        elapsed = time.perf_counter() - t0
        with open(time_path, encoding="utf-8") as f:
            fields = f.read().split()
        if proc.returncode != 0:
            raise SystemExit(
                "command failed (%d): %s\nstderr:\n%s"
                % (proc.returncode, " ".join(command), proc.stderr[-4000:])
            )
        wall = float(fields[0])
        rss = int(fields[1])
        with open(stdout_path, "w", encoding="utf-8") as f:
            f.write(proc.stdout)
        return wall, rss, proc.stdout
    finally:
        try:
            os.unlink(time_path)
        except OSError:
            pass


def python_run(args, out_path):
    command = [
        args.python,
        args.reference,
        "--csv",
        args.csv,
        "--train-start",
        str(args.train_start),
        "--train-end",
        str(args.train_end),
        "--test-start",
        str(args.test_start),
        "--test-end",
        str(args.test_end),
        "--cost-bps",
        str(args.cost_bps),
        "--periods-per-year",
        str(args.periods_per_year),
    ]
    wall, rss, text = timed(command, out_path)
    return wall, rss, json.loads(text)


def rust_run(args, out_path):
    window = "%s,%d,%d,%d,%d" % (
        "bench",
        args.train_start,
        args.train_end,
        args.test_start,
        args.test_end,
    )
    command = [
        args.rcsr,
        "walkforward",
        "--data",
        args.store,
        "--target",
        "y60",
        "--expr",
        "r16",
        "--time",
        "ts",
        "--group-by",
        "symbol",
        "--horizon",
        str(args.horizon),
        "--window",
        window,
        "--cost-bps",
        str(args.cost_bps),
        "--threshold-quantile",
        "0.7",
        "--periods-per-year",
        str(args.periods_per_year),
        "--json",
    ]
    wall, rss, text = timed(command, out_path)
    return wall, rss, json.loads(text)


def median(values):
    return statistics.median(values)


def write_markdown(path, report):
    c = report["comparison"]
    p = report["protocol"]
    lines = [
        "# Issue #124: Rust vs the pinned row-wise Python reference",
        "",
        "Generated by `benchmarks/eval_10x.py`; do not edit by hand.",
        "",
        "## Protocol",
        "",
        "| field | value |",
        "|---|---|",
        "| corpus | `panel_hourly_compact.csv` (Python) / `panel_hourly_v2.rcsb` (Rust) |",
        "| rows x columns | 3,943,856 x 56 |",
        "| window | train `[%s, %s)`, test `[%s, %s)` |" % (
            p["train_start"], p["train_end"], p["test_start"], p["test_end"]
        ),
        "| score / target | `r16` / `y60` |",
        "| position rule | long if `score > q70(train scores)`, else flat |",
        "| costs | %s bp per side on `|position - previous|` per symbol |" % p["cost_bps"],
        "| annualisation | %s periods/year |" % p["periods_per_year"],
        "| Python | `%s` (row-wise `csv.reader`, stdlib only) |" % p["reference_sha256"],
        "| CSV SHA-256 | `%s` |" % report["artifacts"]["csv_sha256"],
        "| store SHA-256 | `%s` |" % report["artifacts"]["store_sha256"],
        "",
        "## Result",
        "",
        "| side | wall (s, median) | peak RSS (KiB, median) | threshold | test rows |",
        "|---|---:|---:|---:|---:|",
        "| Python row-wise | %.3f | %d | %.17g | %d |" % (
            c["python_wall_median"],
            c["python_rss_kib_median"],
            c["python_threshold"],
            c["python_test_rows"],
        ),
        "| Rust `rcsr walkforward` | %.3f | %d | %.17g | %d |" % (
            c["rust_wall_median"],
            c["rust_rss_kib_median"],
            c["rust_threshold"],
            c["rust_test_rows"],
        ),
        "",
        "- **Wall ratio:** **%.1fx** (target: at least 10x)." % c["wall_ratio"],
        "- **RSS ratio:** %.2fx." % c["rss_ratio"],
        "- **Threshold equality:** %s (absolute delta %.3g, tolerance %g)." % (
            "yes" if c["threshold_equal"] else "NO",
            c["threshold_abs_delta"],
            report["gate"]["threshold_tolerance"],
        ),
        "- **Test-row delta:** %d (Rust drops non-finite score/target rows; the "
        "Python reference charges the cost and keeps them)." % c["test_row_delta"],
        "- **Passes 10x:** %s." % ("yes" if c["passes_10x"] else "NO"),
        "",
        "## Repeats",
        "",
        "| side | run | wall (s) | peak RSS (KiB) |",
        "|---|---:|---:|---:|",
    ]
    for side in ("python", "rust"):
        for i, run in enumerate(report["runs"][side], 1):
            lines.append("| %s | %d | %.3f | %d |" % (side, i, run["wall_seconds"], run["peak_rss_kib"]))
    lines += [
        "",
        "## Protocol note",
        "",
        "The reference is the pilot's row-wise CSV loop, not a vectorised or",
        "pandas rewrite. It is the program the Rust evaluator replaces: same",
        "`csv.reader` row order, same q70 formula, same per-symbol position",
        "changes, same equal-weight timestamp aggregation. Comparing against a",
        "different (optimised) program would measure a different reference and",
        "would not support the issue's 10x claim. See `docs/eval-benchmark.md`.",
        "",
    ]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", default=os.environ.get("RCSR_BENCH_CSV", DEFAULT_CSV))
    ap.add_argument("--store", default=os.environ.get("RCSR_BENCH_STORE", DEFAULT_STORE))
    ap.add_argument("--rcsr", default=os.environ.get("RCSR_BENCH_RCSR", DEFAULT_RCSR))
    ap.add_argument("--reference", default=DEFAULT_REFERENCE)
    ap.add_argument("--python", default=os.environ.get("RCSR_BENCH_PYTHON", sys.executable))
    ap.add_argument("--train-start", type=int, default=1609459200)
    ap.add_argument("--train-end", type=int, default=1704067200)
    ap.add_argument("--test-start", type=int, default=1704240000)
    ap.add_argument("--test-end", type=int, default=1735689600)
    ap.add_argument("--horizon", type=int, default=172800)
    ap.add_argument("--cost-bps", type=float, default=10.0)
    ap.add_argument("--periods-per-year", type=float, default=8760.0)
    ap.add_argument("--repeats", type=int, default=2)
    ap.add_argument("--threshold-tolerance", type=float, default=1e-12)
    ap.add_argument("--min-ratio", type=float, default=10.0)
    ap.add_argument("--json", default=DEFAULT_JSON)
    ap.add_argument("--markdown", default=DEFAULT_MARKDOWN)
    ap.add_argument("--check", action="store_true", help="exit non-zero if the threshold or 10x gate fails")
    args = ap.parse_args(argv)

    for path in (args.csv, args.store, args.rcsr, args.reference):
        if not os.path.exists(path):
            raise SystemExit("missing required artifact: %s" % path)

    workdir = tempfile.mkdtemp(prefix="rcsr-eval-10x-")
    runs = {"python": [], "rust": []}
    parsed = {"python": [], "rust": []}
    try:
        for i in range(args.repeats):
            wall, rss, out = python_run(args, os.path.join(workdir, "python-%d.json" % i))
            runs["python"].append({"wall_seconds": wall, "peak_rss_kib": rss})
            parsed["python"].append(out)
            wall, rss, out = rust_run(args, os.path.join(workdir, "rust-%d.json" % i))
            runs["rust"].append({"wall_seconds": wall, "peak_rss_kib": rss})
            parsed["rust"].append(out)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    py = parsed["python"][0]
    rust = parsed["rust"][0]
    rust_window = rust["windows"][0]
    py_wall = median([r["wall_seconds"] for r in runs["python"]])
    rust_wall = median([r["wall_seconds"] for r in runs["rust"]])
    py_rss = median([r["peak_rss_kib"] for r in runs["python"]])
    rust_rss = median([r["peak_rss_kib"] for r in runs["rust"]])
    tau_delta = abs(py["threshold"] - rust_window["threshold"])
    threshold_equal = tau_delta <= args.threshold_tolerance
    wall_ratio = py_wall / rust_wall if rust_wall else float("inf")
    rss_ratio = py_rss / rust_rss if rust_rss else float("inf")

    report = {
        "issue": 124,
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "host": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "processor": platform.processor(),
            "python_version": platform.python_version(),
            "python_implementation": platform.python_implementation(),
        },
        "artifacts": {
            "csv": os.path.abspath(args.csv),
            "csv_bytes": os.path.getsize(args.csv),
            "csv_sha256": sha256(args.csv),
            "store": os.path.abspath(args.store),
            "store_bytes": os.path.getsize(args.store),
            "store_sha256": sha256(args.store),
            "reference": os.path.abspath(args.reference),
            "reference_sha256": sha256(args.reference),
            "rcsr": os.path.abspath(args.rcsr),
            "rcsr_sha256": sha256(args.rcsr),
        },
        "protocol": {
            "train_start": args.train_start,
            "train_end": args.train_end,
            "test_start": args.test_start,
            "test_end": args.test_end,
            "horizon": args.horizon,
            "score": "r16",
            "target": "y60",
            "group_by": "symbol",
            "threshold_quantile": 0.7,
            "cost_bps": args.cost_bps,
            "periods_per_year": args.periods_per_year,
            "reference_sha256": sha256(args.reference),
            "reference_kind": "row-wise csv.reader, stdlib only, not vectorised",
            "warm_cache": "two repeats after the first full scan; the first repeat is reported too",
            "rss_source": "/usr/bin/time -f '%e %M' (maximum resident set size, KiB)",
        },
        "runs": runs,
        "comparison": {
            "python_wall_median": py_wall,
            "rust_wall_median": rust_wall,
            "python_rss_kib_median": py_rss,
            "rust_rss_kib_median": rust_rss,
            "wall_ratio": wall_ratio,
            "rss_ratio": rss_ratio,
            "python_threshold": py["threshold"],
            "rust_threshold": rust_window["threshold"],
            "threshold_abs_delta": tau_delta,
            "threshold_equal": threshold_equal,
            "python_test_rows": py["test_rows"],
            "rust_test_rows": rust_window["test_rows"],
            "rust_dropped_rows": rust_window.get("dropped_rows", 0),
            "test_row_delta": rust_window["test_rows"] - py["test_rows"],
            "python_sharpe": py["sharpe"],
            "rust_sharpe": rust["pooled"]["sharpe"],
            "passes_10x": wall_ratio >= args.min_ratio,
        },
        "gate": {
            "threshold_tolerance": args.threshold_tolerance,
            "min_ratio": args.min_ratio,
            "passed": threshold_equal and wall_ratio >= args.min_ratio,
        },
    }

    os.makedirs(os.path.dirname(os.path.abspath(args.json)), exist_ok=True)
    with open(args.json, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, sort_keys=True)
        f.write("\n")
    if args.markdown:
        write_markdown(args.markdown, report)

    c = report["comparison"]
    print(
        "threshold python=%.17g rust=%.17g delta=%.3g equal=%s"
        % (c["python_threshold"], c["rust_threshold"], c["threshold_abs_delta"], c["threshold_equal"])
    )
    print(
        "wall python=%.3fs rust=%.3fs ratio=%.1fx | rss python=%dKiB rust=%dKiB ratio=%.2fx"
        % (
            c["python_wall_median"],
            c["rust_wall_median"],
            c["wall_ratio"],
            c["python_rss_kib_median"],
            c["rust_rss_kib_median"],
            c["rss_ratio"],
        )
    )
    print("rows python=%d rust=%d delta=%d" % (c["python_test_rows"], c["rust_test_rows"], c["test_row_delta"]))
    print("report: %s\nmarkdown: %s" % (args.json, args.markdown))

    if args.check and not report["gate"]["passed"]:
        print("GATE FAILED", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
